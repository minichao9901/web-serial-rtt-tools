// Keep the downloaded launcher/server identical to the maintained scripts.
import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
const root=new URL('../../',import.meta.url);
const entries=['etm-launcher.ps1'].map(name=>{
  const src=readFileSync(new URL('tools/dev/'+name,root),'utf8').replace(/\r\n/g,'\n');
  return [name,{src,sha256:createHash('sha256').update(src).digest('hex')}];
});
writeFileSync(new URL('app/gen/etm-kit-src.js',root),'// Generated by tools/dev/embed-etm-kit.mjs; do not edit.\nexport const ETM_SCRIPTS = '+JSON.stringify(Object.fromEntries(entries))+';\n');
